const DICTS: Record<Language, Partial<Record<StringKey, string>>> = { en, es, fr };

export function translate(lang: Language, key: StringKey, vars: Record<string, string | number> = {}): string {
  const text = DICTS[lang][key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
}

// The translator for the current language setting. Components use it so they update when the language changes.
export function useT() {
  const lang = usePrefs((s) => s.language);
  return (key: StringKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
}
